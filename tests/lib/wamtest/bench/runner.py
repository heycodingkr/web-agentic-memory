"""Execute a pre-written crossover plan, retain every run, and compare conditions.

adapter(context, spec) must return a bool from an independent oracle and emit a
done/failed event. Real host adapters own their processes and must use the guard
before executing actions. Replay is explicitly uncontrolled evidence.
"""
import copy
import hashlib
import json
from pathlib import Path

from ..evidence import RunDir
from ..procs import Isolation
from . import invalid, repeatability, schedule, stats, trace
from .context import ActionBlocked, RunContext

COMPARISON_METADATA = ("host", "model", "effort", "prompt_hash", "tools_hash")


def _write_json(path, value):
    path.write_text(json.dumps(value, ensure_ascii=False, indent=2, allow_nan=False) + "\n", encoding="utf-8")


def summarize(plan, rows, *, controlled=False, n_boot=10000):
    suite_invalid_rate = sum(bool(row["invalid"]) for row in rows) / len(rows)
    comparisons = {}
    repeatability_by_task = {}
    for task in plan["tasks"]:
        task_rows = [row for row in rows if row["task"] == task]
        repeatability_by_task[task] = {
            condition: repeatability.assess([
                row.get("tts") for row in task_rows
                if row["condition"] == condition and not row["invalid"]
            ])
            for condition in plan["conditions"]
        }
        baseline = [row for row in task_rows if row["condition"] == "T"]
        comparisons[task] = {}
        for condition in plan["conditions"]:
            if condition == "T":
                continue
            other = [row for row in task_rows if row["condition"] == condition]
            result = stats.compare_condition(
                baseline, other, uncontrolled=not controlled, seed=plan["seed"], n_boot=n_boot,
            )
            if suite_invalid_rate > invalid.INVALID_LIMIT:
                result["grade"] = "invalid"
            comparisons[task][condition] = result
    return {
        "runs": len(rows), "successes": sum(row["success"] for row in rows),
        "invalid_rate": suite_invalid_rate, "suite_valid": suite_invalid_rate <= invalid.INVALID_LIMIT,
        "controlled": controlled, "comparisons": comparisons, "repeatability": repeatability_by_task,
    }


def _execute(spec, adapter, evidence, isolation, allow_hosts, controlled=False):
    context = RunContext(evidence, isolation, allow_hosts)
    oracle_pass = False
    try:
        oracle_pass = adapter(context, copy.deepcopy(spec))
        if type(oracle_pass) is not bool:
            raise ValueError("adapter must return an independent oracle bool")
    except ActionBlocked:
        # A blocked unsafe attempt is a real failure, not an environmental exclusion.
        if not context.events or context.events[-1]["type"] not in ("done", "failed"):
            context.event("failed", reason="blocked-action")
    except Exception as error:
        context.signal("harness-error")
        evidence.meta["adapter_error"] = type(error).__name__
    metrics = trace.analyze(context.events)
    if getattr(adapter, "replay_only", False):
        # Replayed monotonic timestamps belong to the recorded trace, while its
        # wall timestamps are generated by this replay run. They cannot be
        # compared as a clock-quality measurement.
        metrics["clock_error_ms"] = None
    if controlled and (metrics["clock_error_ms"] is None or metrics["clock_error_ms"] > 100):
        context.signal("clock-skew")
    invalid_class = invalid.classify_run({"signals": context.signals, "events": context.events})
    success = oracle_pass and metrics["end"] == "done" and not metrics["blocked_actions"] and not invalid_class
    row = {
        **spec, **metrics, "tts": metrics.get("tts"), "calls": metrics.get("calls_to_submit"),
        "errors": metrics["tool_errors"] + metrics["blocked_actions"],
        "success": bool(success), "invalid": invalid_class is not None,
        "invalid_class": invalid_class, "signals": context.signals,
    }
    evidence.meta["invalid_class"] = invalid_class
    evidence.meta["observed_terminal_event"] = metrics["end"]
    evidence.sink("result.json", json.dumps(row, ensure_ascii=False, allow_nan=False))
    evidence.case(
        spec["run_id"], "skip" if invalid_class else ("pass" if success else "fail"),
        expected="independent oracle pass", actual=row,
        reason=invalid_class,
    )
    # RunDir's automatic ending is bookkeeping; it must not make a silent adapter valid.
    if metrics["end"] is None:
        evidence.event("failed", origin="runner", reason=invalid_class or "missing-terminal")
    return row


def run_plan(plan, adapter, output, *, metadata=None, controlled=False,
             allow_hosts=("localhost", "127.0.0.1", "::1"), n_boot=10000):
    """Write the plan before any adapter call. Each run gets a fresh disposable profile."""
    plan = copy.deepcopy(plan)
    problems = schedule.check_balance(plan)
    if problems:
        raise ValueError("; ".join(problems))
    if type(plan.get("seed")) is not int:
        raise ValueError("plan needs an integer seed")
    if "T" not in plan["conditions"]:
        raise ValueError("plan needs the T baseline condition")
    if schedule.fixed_order(plan):
        raise ValueError("fixed condition order is not a valid crossover")
    if type(n_boot) is not int or n_boot < 1:
        raise ValueError("n_boot must be a positive integer")
    if controlled and getattr(adapter, "replay_only", False):
        raise ValueError("replay cannot be a controlled live comparison")
    if controlled and not getattr(adapter, "controlled_ready", True):
        raise ValueError("host adapter has no verified controlled-comparison boundary")
    metadata = copy.deepcopy(metadata or {})
    if controlled and any(not metadata.get(key) for key in COMPARISON_METADATA):
        raise ValueError("controlled comparison needs host/model/effort/prompt_hash/tools_hash")
    ordered = sorted(
        plan["runs"], key=lambda row: (row["block"], plan["tasks"].index(row["task"]), row["position"]),
    )
    plan["runs"] = ordered
    output = Path(output)
    output.mkdir(parents=True, exist_ok=False)
    _write_json(output / "plan.json", plan)
    plan_hash = hashlib.sha256((output / "plan.json").read_bytes()).hexdigest()
    _write_json(output / "meta.json", {**metadata, "controlled": controlled, "plan_sha256": plan_hash})
    rows = []
    with (output / "results.jsonl").open("x", encoding="utf-8") as results:
        for index, spec in enumerate(ordered, 1):
            isolation = Isolation("benchmark")
            try:
                with RunDir("runs", run_id=f"{index:04d}", root=output, host=metadata,
                            extra_meta={"spec": spec, "plan_sha256": plan_hash}) as evidence:
                    row = _execute(spec, adapter, evidence, isolation, allow_hosts, controlled=controlled)
            finally:
                isolation.cleanup()
            rows.append(row)
            results.write(json.dumps(row, ensure_ascii=False, allow_nan=False) + "\n")
            results.flush()
    summary = summarize(plan, rows, controlled=controlled, n_boot=n_boot)
    _write_json(output / "summary.json", summary)
    lines = [
        "# Benchmark results", "",
        f"Runs: {len(rows)}; invalid: {summary['invalid_rate']:.0%}; controlled: {controlled}.", "",
        "| Task / condition | n | TTS | Calls | Successes | Errors | Invalid | Grade |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for task, conditions in summary["comparisons"].items():
        for condition, result in conditions.items():
            lines.append(stats.markdown_row(f"{task} / {condition}", result))
    (output / "summary.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    return summary
